//! cantrip-hwdetect — chwd-style hardware detection for Nethix.
//!
//! Scans /sys/bus/pci/devices, maps vendor:device + class to:
//!  - recommended kernel drivers
//!  - VIDEO_CARDS / INPUT_DEVICES make.conf values
//!  - suggested firmware packages
//! Emits a shell snippet suitable for appending to /etc/portage/make.conf.

use anyhow::Result;
use std::fmt::Write as _;

const VENDOR_AMD: u16 = 0x1002;
const VENDOR_AMD_MODERN: u16 = 0x1022;
const VENDOR_NVIDIA: u16 = 0x10de;
const VENDOR_INTEL: u16 = 0x8086;

const CLASS_VGA: u8 = 0x03;
const CLASS_NET: u8 = 0x02;
const CLASS_AUDIO_HDA: u8 = 0x04;

#[derive(Debug)]
struct PciDev {
    vendor: u16,
    device: u16,
    class: u8,
}

fn parse_u16(s: &str) -> Option<u16> {
    u16::from_str_radix(s.trim().trim_start_matches("0x"), 16).ok()
}

fn scan_pci() -> Result<Vec<PciDev>> {
    let mut devs = Vec::new();
    for entry in std::fs::read_dir("/sys/bus/pci/devices")? {
        let p = entry?.path();
        let (Some(vendor), Some(device)) = (
            std::fs::read_to_string(p.join("vendor")).ok().and_then(|s| parse_u16(&s)),
            std::fs::read_to_string(p.join("device")).ok().and_then(|s| parse_u16(&s)),
        ) else { continue };
        // class file is 0xXXXXXX, top byte = base class
        let class = std::fs::read_to_string(p.join("class"))
            .ok()
            .and_then(|s| u32::from_str_radix(s.trim().trim_start_matches("0x"), 16).ok())
            .map(|c| ((c >> 16) & 0xff) as u8)
            .unwrap_or(0);
        devs.push(PciDev { vendor, device, class });
    }
    Ok(devs)
}

fn video_cards(devs: &[PciDev]) -> Vec<&'static str> {
    let mut cards = vec!["fbdev"];
    let mut has_gpu = false;
    for d in devs {
        if d.class != CLASS_VGA { continue }
        has_gpu = true;
        match d.vendor {
            VENDOR_AMD | VENDOR_AMD_MODERN => cards.push("amdgpu"),
            VENDOR_NVIDIA => {
                // nouveau by default; proprietary is a cantrip-kernel choice later
                cards.push("nouveau");
            }
            VENDOR_INTEL => cards.push("intel"),
            _ => {}
        }
    }
    if !has_gpu { cards.push("vesa") }
    cards.sort();
    cards.dedup();
    cards
}

fn net_drivers(devs: &[PciDev]) -> Vec<&'static str> {
    // real mapping needs pci.ids + kernel module aliases; coarse start
    devs.iter()
        .filter(|d| d.class == CLASS_NET)
        .map(|d| match d.vendor {
            VENDOR_INTEL => "igc/ixgbe (intel)",
            VENDOR_AMD | VENDOR_AMD_MODERN => "r8169-family check",
            VENDOR_NVIDIA => "forcedeth",
            _ => "unknown ethernet",
        })
        .collect()
}

fn firmware_pkgs(devs: &[PciDev]) -> Vec<&'static str> {
    let mut fw = vec!["sys-kernel/linux-firmware"];
    if devs.iter().any(|d| d.class == CLASS_VGA && (d.vendor == VENDOR_AMD || d.vendor == VENDOR_AMD_MODERN)) {
        fw.push("video_cards_amdgpu firmware: amdgpu blobs in linux-firmware");
    }
    if devs.iter().any(|d| d.class == CLASS_AUDIO_HDA) {
        fw.push("audio: sof-firmware check");
    }
    fw
}

fn main() -> Result<()> {
    let devs = scan_pci()?;
    if devs.is_empty() {
        eprintln!("cantrip-hwdetect: no PCI devices found");
        return Ok(());
    }

    let mut out = String::new();
    let _ = writeln!(out, "# generated by cantrip-hwdetect");
    let _ = writeln!(out, "VIDEO_CARDS=\"{}\"", video_cards(&devs).join(" "));
    let _ = writeln!(out, "INPUT_DEVICES=\"libinput\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "# net drivers detected:");
    for n in net_drivers(&devs) { let _ = writeln!(out, "#   {n}"); }
    let _ = writeln!(out, "# firmware to install:");
    for f in firmware_pkgs(&devs) { let _ = writeln!(out, "#   {f}"); }

    println!("{out}");
    Ok(())
}
