//! forge — chwd-style hardware detection for Nethix.
//! Scans /sys/bus/pci/devices, maps vendor:device + class to VIDEO_CARDS,
//! INPUT_DEVICES, suggested drivers and firmware. Emits a make.conf snippet.

use anyhow::Result;
use std::fmt::Write as _;

const VENDOR_AMD: u16 = 0x1002;
const VENDOR_AMD_MODERN: u16 = 0x1022;
const VENDOR_NVIDIA: u16 = 0x10de;
const VENDOR_INTEL: u16 = 0x8086;

const CLASS_VGA: u8 = 0x03;

#[derive(Debug)]
struct PciDev {
    vendor: u16,
    device: u16,
    class: u8,
}

fn parse_u16(s: &str) -> Option<u16> {
    u16::from_str_radix(s.trim().trim_start_matches("0x"), 16).ok()
}

fn scan_pci() -> Result<Vec<PciDev>> {
    let mut devs = Vec::new();
    for entry in std::fs::read_dir("/sys/bus/pci/devices")? {
        let p = entry?.path();
        let (Some(vendor), Some(device)) = (
            std::fs::read_to_string(p.join("vendor")).ok().and_then(|s| parse_u16(&s)),
            std::fs::read_to_string(p.join("device")).ok().and_then(|s| parse_u16(&s)),
        ) else { continue };
        let class = std::fs::read_to_string(p.join("class"))
            .ok()
            .and_then(|s| u32::from_str_radix(s.trim().trim_start_matches("0x"), 16).ok())
            .map(|c| ((c >> 16) & 0xff) as u8)
            .unwrap_or(0);
        devs.push(PciDev { vendor, device, class });
    }
    Ok(devs)
}

fn video_cards(devs: &[PciDev]) -> Vec<&'static str> {
    let mut cards = vec!["fbdev"];
    for d in devs {
        if d.class != CLASS_VGA { continue }
        match d.vendor {
            VENDOR_AMD | VENDOR_AMD_MODERN => cards.push("amdgpu"),
            VENDOR_NVIDIA => cards.push("nouveau"),
            VENDOR_INTEL => cards.push("intel"),
            _ => {}
        }
    }
    cards.sort();
    cards.dedup();
    cards
}

/// Coarse driver notes for NICs and audio (will become pci.ids-backed).
fn device_notes(devs: &[PciDev]) -> Vec<String> {
    let mut notes = Vec::new();
    for d in devs {
        match (d.class, d.vendor) {
            (0x02, VENDOR_INTEL) => notes.push("ethernet: intel igc/ixgbe family".into()),
            (0x02, VENDOR_REALTEK) => notes.push("ethernet: r8169".into()),
            (0x04, _) => notes.push("audio: HDA — check snd_hda_intel / sof-firmware".into()),
            _ => {}
        }
    }
    notes
}

const VENDOR_REALTEK: u16 = 0x10ec;

fn main() -> Result<()> {
    let devs = scan_pci()?;
    let mut out = String::new();
    let _ = writeln!(out, "# generated by forge");
    let _ = writeln!(out, "VIDEO_CARDS=\"{}\"", video_cards(&devs).join(" "));
    let _ = writeln!(out, "INPUT_DEVICES=\"libinput\"");
    for n in device_notes(&devs) {
        let _ = writeln!(out, "# {n}");
    }
    println!("{out}");
    Ok(())
}
